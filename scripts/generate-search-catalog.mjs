import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import vm from 'node:vm';

const root = resolve(import.meta.dirname, '..');
const jsRoot = join(root, 'assets', 'js');
const naturalSort = new Intl.Collator('en', { numeric: true }).compare;

function runSource(source, filename, initialWindow = {}) {
  const context = vm.createContext({ window: initialWindow, console });
  new vm.Script(source, { filename }).runInContext(context);
  return context.window;
}

function runFiles(files, initialWindow = {}) {
  const context = vm.createContext({ window: initialWindow, console });
  files.forEach((file) => {
    new vm.Script(readFileSync(join(jsRoot, file), 'utf8'), { filename: file }).runInContext(context);
  });
  return context.window;
}

const bootstrap = readFileSync(join(jsRoot, 'books-data.js'), 'utf8');
const pinnedUrl = bootstrap.match(/var base = '([^']+)'/)?.[1];
if (!pinnedUrl) throw new Error('Could not find the pinned base-book catalog URL');

const response = await fetch(pinnedUrl);
if (!response.ok) throw new Error(`Could not download pinned book catalog (${response.status})`);
const baseBookWindow = runSource(await response.text(), pinnedUrl);
const bookWindow = runFiles(['books-extra.js'], {
  ALL_BOOKS: Array.from(baseBookWindow.ALL_BOOKS || []),
  BOOKS_CATEGORIES: Array.from(baseBookWindow.BOOKS_CATEGORIES || []),
});

const fatwaFiles = readdirSync(jsRoot)
  .filter((file) => file === 'fatawa-data.js' || /^fatawa-(?:expand-old|extra)\d*\.js$/.test(file))
  .sort(naturalSort);
const fatwaWindow = runFiles(fatwaFiles);

const bookCategories = new Map((bookWindow.BOOKS_CATEGORIES || []).map((category) => [category.id, category.label]));
const fatwaCategories = new Map((fatwaWindow.FATAWA_CATEGORIES || []).map((category) => [category.id, category.label]));

const bookEntries = (bookWindow.ALL_BOOKS || []).map((book) => ({
  type: `كتاب - ${bookCategories.get(book.category) || book.category}`,
  title: `${book.title} — ${book.author}`,
  tags: [book.title, book.author, bookCategories.get(book.category) || book.category],
  url: `book.html?book=${encodeURIComponent(book.id)}`,
}));

const fatwaEntries = (fatwaWindow.FATAWA_DATA || []).map((fatwa) => ({
  type: `فتوى - ${fatwaCategories.get(fatwa.category) || fatwa.category}`,
  title: fatwa.q,
  tags: [fatwa.source, fatwaCategories.get(fatwa.category) || fatwa.category],
  url: `fatawa.html?fatwa=${encodeURIComponent(fatwa.id)}`,
}));

const entries = [...bookEntries, ...fatwaEntries];
const output = `/* Generated by npm run generate:search. Do not edit manually. */\nwindow.SEARCH_CATALOG = ${JSON.stringify(entries)};\n`;
writeFileSync(join(jsRoot, 'search-catalog.js'), output, 'utf8');
console.log(`Generated search catalog: ${bookEntries.length} books and ${fatwaEntries.length} fatwas (${entries.length} entries).`);
